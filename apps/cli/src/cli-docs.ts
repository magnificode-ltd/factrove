import {
  cliCommands,
  cliFlags,
  flagLabel,
  type CliCommandSpec,
  type CliFlagSpec,
} from "./command-spec.js";

export type GeneratedCliPage = {
  slug: string;
  path: string;
  mdx: string;
};

export type CliNavigationGroup = {
  group: string;
  pages: string[];
};

const GENERATED_BANNER = "{/* Generated by `pnpm docs:cli` from apps/cli/src/command-spec.ts. Do not edit by hand. */}";

export function renderCliReferencePages(): GeneratedCliPage[] {
  return cliCommands.map((command) => ({
    slug: command.docsSlug,
    path: `cli-reference/${command.docsSlug}.mdx`,
    mdx: renderCommandPage(command),
  }));
}

export function renderCliNavigation(): CliNavigationGroup {
  return {
    group: "Commands",
    pages: ["cli-reference/overview", ...cliCommands.map((command) => `cli-reference/${command.docsSlug}`)],
  };
}

function renderCommandPage(command: CliCommandSpec): string {
  const flags = commandFlags(command);
  const aliases = [
    ...command.aliases,
    ...command.invocations
      .map((invocation) => invocation.join(" "))
      .filter((name) => name !== command.name),
  ];
  const uniqueAliases = [...new Set(aliases)];

  const lines = [
    "---",
    `title: ${yamlString(command.name)}`,
    `description: ${yamlString(command.summary)}`,
    "---",
    "",
    GENERATED_BANNER,
    "",
    escapeMdx(command.description),
    "",
    "## Usage",
    "",
    ...command.usage.map((line) => `\`\`\`bash\n${line}\n\`\`\``),
    "",
  ];

  if (uniqueAliases.length > 0) {
    lines.push("## Aliases", "", uniqueAliases.map((alias) => `\`${alias}\``).join(", "), "");
  }

  if (command.positionals.length > 0) {
    lines.push("## Arguments", "");
    for (const positional of command.positionals) {
      const required = positional.required ? "required" : "optional";
      lines.push(`<ParamField path="${positional.name}" body required={${positional.required}}>`);
      lines.push(`${escapeMdx(positional.description)} (${required}.)`);
      lines.push("</ParamField>", "");
    }
  }

  lines.push("## Flags", "");
  if (flags.length === 0) {
    lines.push("This command has no flags.", "");
  } else {
    for (const flag of flags) {
      lines.push(renderFlag(flag));
    }
  }

  if (command.examples.length > 0) {
    lines.push("## Examples", "");
    for (const example of command.examples) {
      if (example.description) {
        lines.push(escapeMdx(example.description), "");
      }
      lines.push("```bash", example.command, "```", "");
    }
  }

  lines.push("## Exit codes", "");
  for (const exit of command.exitCodes) {
    lines.push(`- \`${exit.code}\`: ${escapeMdx(exit.description)}`);
  }
  lines.push("");

  if (command.notes.length > 0) {
    lines.push("## Notes", "");
    for (const note of command.notes) {
      lines.push(`- ${escapeMdx(note)}`);
    }
    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}

function commandFlags(command: CliCommandSpec): CliFlagSpec[] {
  const allowed = new Set(command.flags);
  return cliFlags.filter((flag) => flag.id !== "help" && (allowed.has(flag.id) || flag.appliesTo === "*"));
}

function renderFlag(flag: CliFlagSpec): string {
  const aliases = flag.names.slice(1);
  const type = flag.kind === "boolean" ? "boolean" : "string";
  const lines = [
    `<ParamField path="${flagLabel(flag)}" query type="${type}">`,
    escapeMdx(flag.description),
  ];
  if (aliases.length > 0) {
    lines.push(`Aliases: ${aliases.map((name) => `\`${name}\``).join(", ")}.`);
  }
  if (flag.values) {
    lines.push(`Values: ${flag.values.map((value) => `\`${value}\``).join(", ")}.`);
  }
  lines.push("</ParamField>", "");
  return lines.join("\n");
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

function escapeMdx(value: string): string {
  return value.replaceAll("{", "\\{").replaceAll("}", "\\}");
}
