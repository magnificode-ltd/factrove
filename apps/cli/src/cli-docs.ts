import { cliCommands, TOP_LEVEL_HELP, type CliCommandSpec } from "./command-spec.js";

export type GeneratedCliPage = {
  slug: string;
  path: string;
  mdx: string;
};

export type CliNavigationGroup = {
  group: string;
  pages: string[];
};

const GENERATED_BANNER = "{/* Generated by `pnpm docs:cli` from apps/cli/src/command-spec.ts. Do not edit by hand. */}";

export function renderCliReferencePages(): GeneratedCliPage[] {
  return [
    {
      slug: "help",
      path: "cli-reference/help.mdx",
      mdx: renderHelpPage("factrove --help", "The exact top-level help text from the CLI.", TOP_LEVEL_HELP),
    },
    ...cliCommands.map((command) => ({
      slug: command.docsSlug,
      path: `cli-reference/${command.docsSlug}.mdx`,
      mdx: renderCommandPage(command),
    })),
  ];
}

export function renderCliNavigation(): CliNavigationGroup {
  return {
    group: "Commands",
    pages: [
      "cli-reference/overview",
      "cli-reference/help",
      ...cliCommands.map((command) => `cli-reference/${command.docsSlug}`),
    ],
  };
}

function renderCommandPage(command: CliCommandSpec): string {
  return renderHelpPage(command.name, command.summary, command.helpText);
}

function renderHelpPage(title: string, description: string, helpText: string): string {
  return [
    "---",
    `title: ${yamlString(title)}`,
    `description: ${yamlString(description)}`,
    "---",
    "",
    GENERATED_BANNER,
    "",
    "```text",
    helpText.replace(/\n$/, ""),
    "```",
    "",
  ].join("\n");
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}
