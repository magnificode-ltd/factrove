import { readdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { cliReferenceFiles, docsJsonWithCliNavigation } from "./docs-cli.mjs";
import { openApiJson } from "./docs-openapi.mjs";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const generatedBanner = "{/* Generated by `pnpm docs:cli` from apps/cli/src/command-spec.ts. Do not edit by hand. */}";

export async function checkGeneratedDocs() {
  const mismatches = [];
  const expectedOpenApi = openApiJson();
  const openApiPath = join(repoRoot, "docs", "api-reference", "openapi.json");
  const actualOpenApi = await readOptional(openApiPath);
  if (actualOpenApi !== expectedOpenApi) {
    mismatches.push(relative(openApiPath));
  }

  const expectedCli = cliReferenceFiles();
  const expectedCliPaths = new Set(expectedCli.map((file) => file.path));
  for (const file of expectedCli) {
    const actual = await readOptional(file.path);
    if (actual !== file.contents) {
      mismatches.push(relative(file.path));
    }
  }

  const docsJsonPath = join(repoRoot, "docs", "docs.json");
  const committedDocsJson = await readOptional(docsJsonPath);
  if (committedDocsJson === null) {
    mismatches.push(relative(docsJsonPath));
  } else {
    const expectedDocsJson = docsJsonWithCliNavigation(committedDocsJson);
    if (committedDocsJson !== expectedDocsJson) {
      mismatches.push(relative(docsJsonPath));
    }
  }

  const cliDir = join(repoRoot, "docs", "cli-reference");
  for (const name of await readdir(cliDir)) {
    const path = join(cliDir, name);
    if (expectedCliPaths.has(path)) {
      continue;
    }
    if (name === "pages.json") {
      mismatches.push(`${relative(path)} (stale generated CLI navigation)`);
      continue;
    }
    if (!name.endsWith(".mdx")) {
      continue;
    }
    const contents = await readOptional(path);
    if (contents?.includes(generatedBanner)) {
      mismatches.push(`${relative(path)} (stale generated CLI page)`);
    }
  }

  const apiDir = join(repoRoot, "docs", "api-reference");
  for (const name of await readdir(apiDir)) {
    if (name === "openapi.json" || !name.endsWith(".mdx")) {
      continue;
    }
    const contents = await readOptional(join(apiDir, name));
    if (contents?.includes(generatedBanner)) {
      mismatches.push(`${relative(join(apiDir, name))} (stale generated API page)`);
    }
  }

  if (mismatches.length > 0) {
    throw new Error(
      `Generated docs are out of date:\n${mismatches.map((path) => `  ${path}`).join("\n")}\nRun: pnpm docs:openapi && pnpm docs:cli`,
    );
  }
}

async function readOptional(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
      return null;
    }
    throw error;
  }
}

function relative(path) {
  return path.startsWith(`${repoRoot}/`) ? path.slice(repoRoot.length + 1) : path;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await checkGeneratedDocs();
}
