import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { renderCliNavigation, renderCliReferencePages } from "../apps/cli/dist/cli-docs.js";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const cliDir = join(repoRoot, "docs", "cli-reference");
const docsJsonPath = join(repoRoot, "docs", "docs.json");
const generatedBanner = "{/* Generated by `pnpm docs:cli` from apps/cli/src/command-spec.ts. Do not edit by hand. */}";

export function cliReferenceFiles() {
  return renderCliReferencePages().map((page) => ({
    path: join(repoRoot, "docs", page.path),
    contents: page.mdx,
  }));
}

export function applyCliNavigation(docs) {
  const navigation = renderCliNavigation();
  const tabs = docs.navigation.tabs.map((tab) => {
    if (tab.tab !== "CLI reference") {
      return tab;
    }
    return { ...tab, groups: [navigation] };
  });
  return {
    ...docs,
    navigation: { ...docs.navigation, tabs },
  };
}

export function docsJsonWithCliNavigation(source) {
  return `${JSON.stringify(applyCliNavigation(JSON.parse(source)), null, 2)}\n`;
}

export async function writeCliReference() {
  await mkdir(cliDir, { recursive: true });
  const existing = await readdir(cliDir);
  for (const name of existing) {
    const path = join(cliDir, name);
    if (name === "pages.json") {
      await unlink(path);
      continue;
    }
    if (!name.endsWith(".mdx")) {
      continue;
    }
    const current = await readFile(path, "utf8");
    if (current.includes(generatedBanner)) {
      await unlink(path);
    }
  }
  const files = cliReferenceFiles();
  for (const file of files) {
    await mkdir(dirname(file.path), { recursive: true });
    await writeFile(file.path, file.contents);
  }
  const docsJson = docsJsonWithCliNavigation(await readFile(docsJsonPath, "utf8"));
  await writeFile(docsJsonPath, docsJson);
  return [...files.map((file) => file.path), docsJsonPath];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeCliReference();
}
